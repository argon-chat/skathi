/// The per-frame JS pump: runs before the frame's draw, so `cx.notify()` from a host fn lands in the same frame.
fn pump_frame(window: &mut Window, cx: &mut App) {
    #[cfg(sk_devtools)]
    let _allocation_scope = crate::heapcount::recording::scope("runtime", "frame/pump");
    // A cloaked or occluded window is a hidden page: decline the pump and, by not stamping the
    // frame clock, hand the window to the background tick. Not before the first frame (boot wave).
    if background::pumped_once() && (window::cloaked() || window::occluded()) {
        idle::rearm_paced(window, pump_frame, idle::CLOAKED_INTERVAL);
        return;
    }
    perf::frame();
    background::note_frame();
    // Before the poison gate: a worker's log is what an agent wants once JS has given up.
    drain_log_tee();
    if sk_runtime::bridge::poisoned() {
        // No JS after a caught native panic: show the fatal dialog once, do not re-arm.
        crash_window::on_poisoned(cx);
        return;
    }
    if first_wave_waits(window) {
        idle::rearm_unpaced(window, pump_frame);
        return;
    }
    // Before the pump, so what the mousemove handler schedules drains this frame.
    sk_tree::flush_pending_mouse_move(window, cx);
    #[cfg(sk_devtools)]
    inspector::poll_frame(cx);
    js_wave(window, cx, Wave::Frame);
    window::note_painted_frame();
    after_wave(window, cx);
    #[cfg(sk_devtools)]
    if devtools::busy() {
        idle::note_moved();
    }
    idle::rearm(window, pump_frame, window::app_focused(cx) || quiet::never_focus());
    perf::pump_done();
    // Observers run after layout and before paint, so this draws ahead of gpui's draw. After
    // `pump_done` so that draw stays in gpui's bucket of the frame trace.
    sk_tree::update_layout_observers(window, cx);
    // The background tick measures the stall from here, so a slow frame is not mistaken for a parked one.
    background::note_frame();
}

#[derive(Clone, Copy, PartialEq, Eq)]
pub(crate) enum Wave {
    Frame,
    /// The window draws no frames: no `requestAnimationFrame`, as in a hidden page.
    Background,
}

/// One JS wave inside one `Phase::Commit` publication.
pub(crate) fn js_wave(window: &mut Window, cx: &mut App, wave: Wave) {
    let focused = window::app_focused(cx) || quiet::never_focus();
    with_published(window, cx, Phase::Commit, || {
        // HMR before the pump, so what Vue schedules while patching drains this frame.
        if wave == Wave::Frame {
            let n = FRAME_NO.with(|f| {
                let n = f.get().wrapping_add(1);
                f.set(n);
                n
            });
            boot_mode::poll_frame(n);
        }
        reload::pump();
        // Before `rt.pump` so `resize` handlers' DOM mutations drain this frame.
        sk_runtime::with_commit(|window, cx| window::pump(window, cx));
        sk_runtime::runtime::set_frame_budget_ms(window::frame_budget_ms());
        let flags = match wave {
            Wave::Frame => PUMP_TIMERS | PUMP_RAF | PUMP_MICROTASKS,
            Wave::Background => PUMP_TIMERS | PUMP_MICROTASKS,
        };
        JsRuntime::with(|rt| {
            let pumped = std::time::Instant::now();
            let stats = rt.pump(flags);
            let elapsed = pumped.elapsed();
            if wave == Wave::Frame {
                #[cfg_attr(not(feature = "audio"), allow(unused_mut))]
                let mut report = idle::Wave::from_stats(&stats, elapsed);
                #[cfg(feature = "audio")]
                {
                    report.audio = sk_runtime::redjs::webapi::audio::busy(rt.raw());
                }
                idle::note_wave(report);
            }
            #[cfg(sk_devtools)]
            devtools::trace::note_js(elapsed.as_secs_f32() * 1000.0);
            for err in rt.drain_errors() {
                eprintln!("[js uncaught] {}\n{}", err.header, err.stack);
                sk_tree::log::record(
                    "error",
                    format!("[js uncaught] {}\n{}", err.header, err.stack),
                );
            }
            reclaim::after_wave(rt, focused, wave == Wave::Background || window::page_hidden());
        });
        // One devtools command per frame, in this publication, so it never sees a half-applied patch.
        #[cfg(sk_devtools)]
        {
            devtools::pump();
        }
        js::frame();
        sk_permissions::pump();
        sk_desktop::pump();
        embed::pump();
        // At most one localStorage file write per frame.
        #[cfg(feature = "storages")]
        sk_storage::pump();
    });
}

/// What follows a JS wave on both clocks. On the background tick the repaint only marks the window dirty.
pub(crate) fn after_wave(window: &mut Window, cx: &mut App) {
    // Media ticks run before the draw so a media element paints this tick's picture. The device
    // check comes first: after a renderer device loss every `<video>` must rebuild before it ticks.
    publish_video_device();
    let media_moved = sk_tree::frame_tick(window, cx);
    let flush = sk_tree::flush_changes_kind();
    let tree_moved = flush != sk_tree::Flush::Unchanged;
    #[cfg(sk_devtools)]
    if tree_moved {
        devtools::ws::note_tree_changed();
    }
    // A hidden page paints no animation. Playing media asks for a draw only via `media_moved`.
    let animating = sk_tree::animating() && !window::page_hidden();
    let moving = animating || media_moved;
    if flush == sk_tree::Flush::DrawnBySync {
        // A forced layout already drew this tree; with no newer work the notify below is skipped.
        sk_tree::perf::note_sync_tail(!moving);
    }
    if flush == sk_tree::Flush::Changed || moving {
        notify_shell(cx);
    }
    if tree_moved || moving {
        // CSS animations alone are not work: an unfocused window paces them.
        if tree_moved || media_moved {
            idle::note_moved();
        } else {
            idle::note_animating();
        }
        // The synchronous layout draws only the primary window.
        popout::notify_all(cx);
    }
    // After the flush, so a socket is never told about a revision the tree has not reached.
    #[cfg(sk_devtools)]
    devtools::ws::broadcast_frame();
}

