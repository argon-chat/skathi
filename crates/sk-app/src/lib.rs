/// Vue's esm-bundler build reads three flags off globalThis (bun refuses to inline them); must run
/// BEFORE the app bundle, since ESM import hoisting would put the bundle's Vue code first.
/// Generated by `bun run preludes` and checked in, so `cargo build` needs no JS toolchain.
const PRELUDE_JS: &str = include_str!("prelude.js");

