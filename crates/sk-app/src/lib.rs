impl Shell {
    fn render_body(&mut self, window: &mut Window, cx: &mut Context<Self>) -> gpui::Div {
        let shell = div()
            .relative()
            .flex()
            .flex_col()
            .size_full()
            .text_color(gpui::white())
            .font_family(".SystemUIFont");
        #[cfg(target_os = "linux")]
        let shell = linux_chrome::wrap(shell, window);
        if !window::fallback_titlebar() {
            return shell
                .child(sk_tree::build_root(window, cx))
                .children(window_controls_overlay())
                .children(inspector_overlay());
        }
        shell
            .child(
                div()
                    .id("titlebar")
                    .window_control_area(WindowControlArea::Drag)
                    .h(px(36.))
                    .px(px(14.))
                    .flex()
                    .items_center()
                    .text_size(px(13.))
                    .child(self.title.clone()),
            )
            // `flex_1().min_h(0)` gives the app root a definite box; an auto-height slot would break
            // `h-full`, `overflow: auto` and `position: fixed` inside the app.
            .child(
                div()
                    .flex_1()
                    .min_h(px(0.))
                    .child(sk_tree::build_root(window, cx)),
            )
            .children(window_controls_overlay())
            .children(inspector_overlay())
    }
}

/// Lives in the shell, not the app's tree, so the inspector never appears in the tree it inspects.
fn inspector_overlay() -> Option<gpui::Div> {
    #[cfg(sk_devtools)]
    {
        devtools::highlight_overlay()
    }
    #[cfg(not(sk_devtools))]
    {
        None
    }
}

/// The host-drawn caption-button cluster (`titleBarOverlay`), top-right.
///
/// `window_control_area` makes `WM_NCHITTEST` answer HTMINBUTTON/HTMAXBUTTON/HTCLOSE, so the OS
/// performs the action and HTMAXBUTTON arms the Windows 11 snap-layouts flyout.
fn window_controls_overlay() -> Option<gpui::Div> {
    let (height, overlay) = window::overlay()?;
    // Win10 has these code points in Segoe MDL2 Assets; `fallbacks` is DirectWrite's per-code-point chain.
    const MIN: &str = "\u{e921}";
    const MAX: &str = "\u{e922}";
    const CLOSE: &str = "\u{e8bb}";
    let glyph_font = gpui::Font {
        family: "Segoe Fluent Icons".into(),
        fallbacks: Some(gpui::FontFallbacks::from_fonts(vec![
            "Segoe MDL2 Assets".to_string(),
            "Segoe UI Symbol".to_string(),
        ])),
        features: Default::default(),
        weight: Default::default(),
        style: Default::default(),
    };
    let symbol = overlay
        .symbol_color
        .map(rgba)
        .unwrap_or_else(|| rgba(0xffffffe0));
    let button = |id: &'static str, glyph: &'static str, area: WindowControlArea, hover: u32| {
        div()
            .id(id)
            .w(px(window::OVERLAY_BUTTON_WIDTH))
            .h(px(height))
            .flex()
            .items_center()
            .justify_center()
            .text_size(px(10.))
            .text_color(symbol)
            .font(glyph_font.clone())
            .window_control_area(area)
            .hover(|s| s.bg(rgba(hover)))
            .child(glyph)
    };
    let mut strip = div()
        .absolute()
        .top_0()
        .right_0()
        .h(px(height))
        .flex()
        .flex_row();
    if let Some(bg) = overlay.color {
        strip = strip.bg(rgba(bg));
    }
    Some(
        strip
            .child(button("wco-min", MIN, WindowControlArea::Min, 0xffffff1a))
            .child(button("wco-max", MAX, WindowControlArea::Max, 0xffffff1a))
            .child(button("wco-close", CLOSE, WindowControlArea::Close, 0xc42b1cff)),
    )
}

/// The directory a relative `<img src>` resolves against: `SK_APP_ROOT`, else [`dev::boot`] derives
/// it from the manifest entry. Prod leaves it unset (working directory, with an advisory).
fn publish_app_root() {
    #[cfg(feature = "prod")]
    if prod::publish_asset_store() {
        return;
    }
    if let Some(dir) = std::env::var_os("SK_APP_ROOT") {
        if !dir.is_empty() {
            sk_tree::set_asset_base(std::path::PathBuf::from(dir));
        }
    }
}

fn install_iframe_backend() {
    #[cfg(feature = "storages")]
    let data = embed::data_dir()
        .map(std::path::Path::to_path_buf)
        .or_else(|| sk_storage::default_folder(boot_mode::app_name().as_deref()).parent().map(std::path::Path::to_path_buf));
    #[cfg(not(feature = "storages"))]
    let data: Option<std::path::PathBuf> = None;
    let user_data = data.unwrap_or_else(|| std::env::temp_dir().join("skathi")).join("webview");
    let config = sk_webview::Config {
        assets: std::rc::Rc::new(|path| sk_tree::read_app_asset(path)),
        user_data,
        page_origin: "app://redjs".into(),
        devtools: !cfg!(feature = "prod"),
    };
    if let Some(backend) = sk_webview::backend(config) {
        sk_tree::iframe::set_backend(backend, std::rc::Rc::new(sk_runtime::frames::wake));
    }
}

/// Closes every `<iframe>` document on quit, so no browser process outlives the app.
fn close_iframes_on_quit(cx: &mut App) {
    std::mem::forget(cx.on_app_quit(|_| {
        sk_tree::iframe::shutdown();
        std::future::ready(())
    }));
}

/// Hands `<video>` the renderer's D3D11 device, again after a device loss (each `<video>` rebuilds,
/// keeping position and transport state). Runs every frame. The pointer is BORROWED from
/// `DirectXDevices`; `sk_video` clones the COM interface if it keeps it.
#[cfg(target_os = "windows")]
fn publish_video_device() {
    use std::cell::Cell;
    #[cfg(feature = "native-dx12")]
    {
        static INSTALL: std::sync::Once = std::sync::Once::new();
        INSTALL.call_once(|| {
            fn provide() -> Result<Option<sk_tree::SharedVideoDevice>, String> {
                gpui_windows::ensure_renderer_d3d11_device()
                    .map(|lease| lease.map(|lease| sk_tree::SharedVideoDevice {
                        device: lease.device,
                        generation: lease.generation,
                        keep_alive: lease.keep_alive,
                    }))
                    .map_err(|error| format!("Could not initialize renderer video bridge: {error:#}"))
            }
            // The renderer's owned lease keeps the raw COM pointer valid.
            if let Err(error) = unsafe { sk_tree::install_video_device_provider(provide) } {
                log::error!("Could not install lazy video device provider: {error}");
            }
        });
    }
    thread_local! {
        /// 0 is never a live generation.
        static PUBLISHED: Cell<u64> = const { Cell::new(0) };
    }
    let (ptr, generation) = gpui_windows::renderer_d3d11_device();
    let previous = PUBLISHED.with(Cell::get);
    if generation == 0 || previous == generation || (ptr.is_null() && previous == 0) {
        return;
    }
    // A new native12 generation has no D3D11 bridge yet: old decoders still rebuild; the next load asks the lazy provider.
    let first = previous == 0;
    PUBLISHED.with(|p| p.set(generation));
    // SAFETY: the pointer comes straight from the live `DirectXDevices`.
    unsafe { sk_tree::set_video_device(ptr, generation) };
    if first {
        return;
    }
    let rebuilt = sk_tree::video_device_changed();
    let msg = format!(
        "[video] the renderer recreated its D3D11 device (generation {generation}) — rebuilt \
         {rebuilt} <video> element(s) on it, resuming where they were"
    );
    eprintln!("{msg}");
    sk_tree::log::record("window", msg);
}

#[cfg(not(target_os = "windows"))]
fn publish_video_device() {}

/// gpui's `Resource::Uri` client is redjs's network stack ([`http_client`]); without one gpui's
/// `NullHttpClient` fails every request. `SK_HTTP_CLIENT=reqwest` swaps in `ReqwestClient`.
fn install_http_client(app: gpui::Application) -> gpui::Application {
    if std::env::var("SK_HTTP_CLIENT").is_ok_and(|v| v.eq_ignore_ascii_case("reqwest")) {
        return match reqwest_client::ReqwestClient::user_agent(concat!("skathi/", env!("CARGO_PKG_VERSION"))) {
            Ok(client) => app.with_http_client(std::sync::Arc::new(client)),
            Err(e) => {
                log::warn!("SK_HTTP_CLIENT=reqwest: the client could not be built ({e}); http(s) images will not load");
                app
            }
        };
    }
    app.with_http_client(std::sync::Arc::new(http_client::RedjsHttpClient::new()))
}

/// The host exe's `main`: this process IS the app.
pub fn run_exe() {
    // First, so a host whose runner is already gone never opens a window.
    owner::watch();
    // The one parse of the command line; consumers never read `std::env::args()`.
    let args = sk_desktop::args::process();
    // `sk build`'s host check: a bare host prints one JSON line and exits. A packaged exe's argv belongs to its app.
    if args.host.host_info && !payload::embedded_present() {
        println!("{}", payload::host_info_json());
        return;
    }
    // `--sk-dist` is `SK_DIST` for a process started for a protocol link (no inherited environment).
    if let Some(dist) = args.host.sk_dist.as_deref().filter(|d| !d.is_empty()) {
        std::env::set_var("SK_DIST", dist);
    }
    // Single instance, before the inspector, logger and gpui: a second launch forwards its
    // argv/url/cwd and exits without a window. The inspector (`--devtools`) is never an instance.
    {
        let launch_cfg = if args.host.devtools { None } else { boot_mode::launch_config() };
        // The instance key is the app's id and storage folder, not the slot.
        #[cfg(not(feature = "prod"))]
        let dev_slot = Some(slot::dir());
        #[cfg(feature = "prod")]
        let dev_slot = None;
        let build_name = if args.host.devtools { None } else { boot_mode::app_name() };
        if let sk_desktop::launch::Outcome::Exit(code) =
            sk_desktop::launch::start(args, launch_cfg.as_deref(), build_name, dev_slot)
        {
            std::process::exit(code);
        }
        if !args.host.devtools {
            sk_desktop::launch::register_declared();
        }
    }
    // `--devtools` rewrites the dist slot and instance env vars: before anything reads them.
    #[cfg(sk_devtools)]
    inspector::init();
    #[cfg(feature = "prod")]
    {
        #[cfg(sk_devtools)]
        let inspecting = inspector::is_devtools_host();
        #[cfg(not(sk_devtools))]
        let inspecting = false;
        if !inspecting {
            prod::require_payload();
        }
    }
    run_app();
    // Ends the process without the C runtime's exit path.
    shutdown::finish();
}

/// The exe's boot without the process-owned parts: the embedder owns the command line and is the
/// instance; the end is reported rather than taken.
pub(crate) fn run_embedded() {
    let args = sk_desktop::args::process();
    if !embed::desktop_launch_prepared() {
        let _ = sk_desktop::launch::start(args, None, boot_mode::app_name(), None);
    }
    run_app();
    shutdown::finish();
}

fn run_app() {
    // Before anything gpui does, so the renderer's boot messages are visible.
    install_logger();
    #[cfg(all(feature = "webgpu", target_os = "windows"))]
    shared_gpu::install().expect("installing shared graphics device provider");
    perf::boot();
    #[cfg(sk_devtools)]
    if heapcount::on() {
        sk_tree::perf::set_live_bytes_probe(|| heapcount::snapshot().map(|s| s.0));
        sk_tree::devtools::set_image_tracking(true);
    }
    // The primary window owns the JS pump; closing it ends the host on every OS (AppKit otherwise keeps a windowless app running).
    let app = install_http_client(application())
        .with_quit_mode(gpui::QuitMode::LastWindowClosed);
    // The show is queued, never applied inside AppKit's callback.
    #[cfg(target_os = "macos")]
    app.on_reopen(|_| embed::reopen());
    #[cfg(feature = "prod")]
    let app = if payload::get().is_some() { app.with_assets(payload::GpuiAssets) } else { app };
    app.run(|cx: &mut App| {
        // `--devtools`: the app is the inspector, from this executable.
        #[cfg(sk_devtools)]
        let devtools_mode = inspector::is_devtools_host();
        #[cfg(not(sk_devtools))]
        let devtools_mode = false;
        sk_elements::init(cx);
        publish_app_root();
        // First quit hook (they run in order): a quit no accepted close announced, such as the
        // session ending, hides the windows and arms the deadline.
        std::mem::forget(cx.on_app_quit(|_| {
            window::cancel_startup_reveal();
            shutdown::begin("quit");
            std::future::ready(())
        }));
        std::mem::forget(cx.on_app_quit(|_| {
            JsRuntime::try_with(|runtime| js::shutdown(runtime.ctx()));
            std::future::ready(())
        }));
        close_iframes_on_quit(cx);
        #[cfg(sk_devtools)]
        {
            inspector::install_hotkey(cx);
            // A debugger must not outlive its subject (the child also watches us, for a crash).
            std::mem::forget(cx.on_app_quit(|_| {
                shutdown::step("inspector", inspector::close_children);
                std::future::ready(())
            }));
        }
        // So a final-frame `Set-Cookie` or `pagehide` `setItem` reaches disk.
        #[cfg(feature = "storages")]
        std::mem::forget(cx.on_app_quit(|_| {
            shutdown::step("storage", || {
                if let Err(e) = sk_storage::flush() {
                    eprintln!("[storage] localStorage: the last change was not written: {e}");
                }
                if let Err(e) = sk_storage::cookies::flush() {
                    eprintln!("[storage] cookies: the last change was not written: {e}");
                }
            });
            shutdown::step("http-cache", sk_runtime::redjs::webapi::http::cache::uninstall);
            std::future::ready(())
        }));
        // Synchronous: gpui gives quit futures only 200 ms.
        #[cfg(feature = "indexeddb")]
        std::mem::forget(cx.on_app_quit(|_| {
            let t = std::time::Instant::now();
            let done = shutdown::step("indexeddb", || sk_runtime::redjs::ffi::redjs_idb_shutdown(2_000));
            if done == 0 {
                eprintln!(
                    "[sk] IndexedDB did not finish closing within {} ms; the next start recovers from its WAL",
                    t.elapsed().as_millis()
                );
            }
            std::future::ready(())
        }));
        shutdown::install_test_delay(cx);
        // Before the runtime exists so the log ring records the first advisory.
        #[cfg(sk_devtools)]
        devtools::arm();

        // The window config is read before `open_window` (creation-time-only options need it to
        // avoid a flash) and before the JS runtime (`"devtools": false` must be answered before a port is bound).
        #[cfg(sk_devtools)]
        let window_json =
            if devtools_mode { inspector::window_config() } else { boot_mode::window_config() };
        #[cfg(not(sk_devtools))]
        let window_json = boot_mode::window_config();
        // The HTTP cache cap rides in the same block; read before it is consumed.
        #[cfg(feature = "storages")]
        let http_cache_mb = http_client::cache_mb(window_json.as_deref());
        let cfg = window::load_config(window_json);

        // Before `JsRuntime::init` so the bundle's first line sees the settled state.
        #[cfg(sk_devtools)]
        devtools::boot(window::devtools_config_enabled());

        // Seeded before `JsRuntime::init` so the first `navigator.onLine` read queues no event.
        sk_desktop::network::install();

        #[cfg(all(sk_devtools, not(feature = "native-aot")))]
        if let Some(summary) = devtools_mode.then(|| inspector::engine_without_native(
            std::env::var_os("SK_DEVTOOLS_ENGINE").as_deref(),
            std::env::var_os("SK_DEVTOOLS_NATIVE_IMAGE").is_some(),
        ).err()).flatten() {
            eprintln!("[native-aot] {summary}");
            embed::finished(false, summary);
            cx.quit();
            return;
        }
        #[cfg(all(sk_devtools, feature = "native-aot"))]
        if let Err(error) = native_aot::prepare(devtools_mode) {
            let summary = format!("native inspector preparation failed: {error}");
            eprintln!("[native-aot] {summary}");
            embed::finished(false, summary);
            cx.quit();
            return;
        }
        JsRuntime::init();
        #[cfg(target_os = "windows")]
        consent_window::install(cx);
        let setup_result = JsRuntime::with(|rt| -> Result<(), String> {
            rt.register("__sk_set_status", 1, sk_set_status as *const _);
            rt.register("__sk_log", 1, sk_log as *const _);
            rt.register("__sk_perf_mark", 1, sk_perf_mark as *const _);
            reload::install(rt);
            sk_tree::install(rt);
            window::install(rt);
            popout::install(rt);
            #[cfg(feature = "audio")]
            microphone::install();
            // gpui's clipboard, the one native <input> uses, so there is one owner of `OpenClipboard`.
            #[cfg(feature = "clipboard")]
            sk_clipboard::install();
            sk_permissions::install(rt);
            sk_locale::install(rt);
            // Without a backend every `<iframe src>` answers `error`.
            if !devtools_mode {
                install_iframe_backend();
            }
            sk_desktop::set_log_sink(|kind, text| sk_tree::log::record(kind, text));
            sk_desktop::install(rt);
            // A file dialog is owned by the window published for the call that asked.
            sk_desktop::dialog::set_owner_resolver(dialogs::owner);
            sk_permissions::set_asker(dialogs::ask_permission);
            sk_permissions::set_app_name(&cfg.title);
            crash_window::set_app_name(&cfg.title);
            // Before any app code: the area loads lazily, so a late install would hand the app an empty `localStorage`.
            #[cfg(feature = "storages")]
            if !devtools_mode {
                let encrypted = embed::storage_encrypted();
                if embed::data_dir().is_some() || encrypted.is_some() {
                    let directory = embed::data_dir().map(std::path::Path::to_path_buf)
                        .unwrap_or_else(|| sk_storage::default_folder(boot_mode::app_name().as_deref()));
                    sk_storage::set_storage_folder(&directory, encrypted)?;
                    if encrypted == Some(true) {
                        sk_storage::encrypt_local_storage_at(&directory)?;
                    }
                }
            }
            #[cfg(feature = "storages")]
            sk_storage::install(
                rt,
                if devtools_mode { Some("sk-devtools".to_string()) } else { boot_mode::app_name() },
            );
            // After `install` (which names the app), before any JS; sealed when storage is.
            #[cfg(feature = "storages")]
            if !devtools_mode {
                if let Some(directory) = embed::data_dir() {
                    sk_storage::http_cache::install_at(http_cache_mb, directory.join("cache").join("http"));
                } else {
                    sk_storage::http_cache::install(http_cache_mb);
                }
            }
            // Without storage the answers last for the run.
            #[cfg(feature = "storages")]
            sk_permissions::set_decisions_file(sk_storage::cookies::folder().map(|f| f.join("permissions.json")));
            // Embedding plugins initialize against the installed storage and cookie jar.
            if !devtools_mode {
                tray::install(rt)?;
                hotkeys::install(rt)?;
                embed::setup(rt)?;
            }
            #[cfg(sk_devtools)]
            devtools::install(rt);
            embed::install(rt);
            Ok(())
        });
        if let Err(error) = setup_result {
            let summary = format!("host setup failed: {error}");
            eprintln!("[embed] {summary}");
            embed::finished(false, summary);
            cx.quit();
            return;
        }

        let bounds = Bounds::centered(None, size(px(cfg.width), px(cfg.height)), cx);
        let startup_visible = embed::visible();
        let startup_focus = !devtools_mode && !quiet::never_focus() && embed::activates();
        let defer_reveal = cfg!(target_os = "windows") && startup_visible;
        if defer_reveal {
            window::begin_startup_reveal();
        }
        cx.open_window(
            WindowOptions {
                window_bounds: Some(WindowBounds::Windowed(bounds)),
                window_background: cfg.backdrop.to_gpui(),
                titlebar: Some(TitlebarOptions {
                    title: Some(cfg.title.clone().into()),
                    // The chrome-mode switch (`!hide_title_bar` adds `WS_CAPTION`): creation-time only.
                    appears_transparent: cfg.title_bar_style == window::TitleBarStyle::Hidden,
                    traffic_light_position: window::traffic_light_position(
                        cfg.title_bar_style == window::TitleBarStyle::Hidden,
                        cfg.title_bar_height,
                    ),
                    ..Default::default()
                }),
                is_resizable: cfg.resizable,
                is_minimizable: cfg.minimizable,
                window_min_size: cfg
                    .min_width
                    .zip(cfg.min_height)
                    .map(|(w, h)| size(px(w), px(h))),
                // The armed pump must not opt the window into the 33 ms unfocused throttle (JS timers would coarsen).
                inactive_frame_interval: None,
                // Maps to `SW_SHOWNOACTIVATE`: F12 shows the inspector without taking the caret from the app.
                show: startup_visible && !defer_reveal,
                focus: startup_focus,
                #[cfg(target_os = "linux")]
                window_decorations: Some(gpui::WindowDecorations::Client),
                #[cfg(target_os = "linux")]
                app_id: embed::desktop_id().or_else(|| sk_desktop::launch::identity().map(|i| i.id.clone())),
                ..Default::default()
            },
            |window, cx| {
                if std::env::var_os("SK_RETAINED_LAYOUT").as_deref() != Some(std::ffi::OsStr::new("0")) {
                    window.vn_enable_retained_layout();
                }
                // Before the first frame is presented, so a test host is never seen in front.
                quiet::send_to_back(window);
                publish_video_device();
                let shell = cx.new(|_| Shell { title: cfg.title.clone() });
                SHELL.with(|s| *s.borrow_mut() = Some(shell.downgrade()));
                window::init(&cfg, window, cx);
                // The pipe thread raises it directly: the foreground grant is short-lived.
                if let Some(hwnd) = window::capture_hwnd(window) {
                    sk_desktop::launch::set_window(hwnd);
                }
                // `beforeunload`: a synchronous boolean.
                window.on_window_should_close(cx, |window, cx| {
                    let closing = window::should_close();
                    if closing {
                        window::cancel_startup_reveal();
                        shutdown::begin("a close request (WM_CLOSE)");
                    }
                    // A pop-out left open would be a live window with no JS clock.
                    if closing && popout::count() > 0 {
                        sk_tree::log::record(
                            "window",
                            format!(
                                "[window] the primary window is closing — taking {} pop-out(s) \
                                 with it",
                                popout::count()
                            ),
                        );
                        popout::close_all(cx);
                    }
                    // A file dialog owned by this window outlives a close request by its own 100 ms timer.
                    closing && dialogs::may_close_now(window.window_handle(), cx)
                });
                window.on_next_frame(pump_frame);
                shell
            },
        )
        .map(|handle| MAIN_WINDOW.with(|w| w.set(Some(handle.into()))))
        .unwrap();
        background::start(cx);
        #[cfg(target_os = "windows")]
        sk_runtime::frames::set_waker(gpui_windows::wake_frames);

        // Before any JS: the bundle's `onMounted` needs layout reads.
        sk_tree::set_sync_layout(sync_layout);
        let text_system = cx.text_system().clone();
        sk_css::set_font_source(move || text_system.all_font_names());
        let metric_system = cx.text_system().clone();
        let metric_text = RefCell::new((0usize, gpui::WindowTextSystem::new(metric_system.clone())));
        sk_css::set_font_metric_source(move |font, size| {
            let mut cache = metric_text.borrow_mut();
            let (queries, text) = &mut *cache;
            // This metric-only window is not frame-pumped: bound its line cache.
            if *queries >= 128 {
                *text = gpui::WindowTextSystem::new(metric_system.clone());
                *queries = 0;
            }
            *queries += 1;
            let run = gpui::TextRun { len: 1, font: font.clone(), color: gpui::black(), ..Default::default() };
            let lines = text.shape_text("0".into(), gpui::px(size), &[run], None, None).ok()?;
            let line = lines.first()?;
            let font_id = line.runs().first()?.font_id;
            Some(sk_css::FontRelativeMetrics {
                zero_advance: f32::from(line.size(gpui::px(size)).width),
                x_height: f32::from(text.x_height(font_id, gpui::px(size))),
            })
        });

        // Host fns called at top level land in Phase::App.
        #[cfg(sk_devtools)]
        let mut startup_error: Option<String> = None;
        with_published_app(cx, || {
            JsRuntime::with(|rt| {
                if let Err(e) = perf::boot_eval("preludes", || rt.eval(PRELUDE_JS, "sk://prelude.js")) {
                    eprintln!("[js boot] {}\n{}", e.header, e.stack);
                    #[cfg(all(sk_devtools, feature = "native-aot"))]
                    if sk_runtime::redjs::aot::is_active() {
                        startup_error = Some(format!("native inspector prelude failed: {}", e.header));
                        return;
                    }
                }
                if let Err(e) = perf::boot_eval("preludes", || rt.eval(WINDOW_PRELUDE_JS, "sk://window.js")) {
                    eprintln!("[js boot] {}\n{}", e.header, e.stack);
                    #[cfg(all(sk_devtools, feature = "native-aot"))]
                    if sk_runtime::redjs::aot::is_active() {
                        startup_error = Some(format!("native inspector prelude failed: {}", e.header));
                        return;
                    }
                }
                // `SK_SCENARIO` pins a harness app to one screen; sanitised, published as a global.
                let scenario = std::env::var("SK_SCENARIO").unwrap_or_default();
                if !scenario.is_empty() {
                    let safe: String = scenario
                        .chars()
                        .filter(|c| c.is_ascii_alphanumeric() || *c == '-' || *c == '_')
                        .collect();
                    let js = format!("globalThis.__SK_SCENARIO__ = \"{safe}\";");
                    if let Err(e) = rt.eval(&js, "sk://scenario.js") {
                        eprintln!("[js boot] {}\n{}", e.header, e.stack);
                    }
                }
                #[cfg(sk_devtools)]
                if devtools_mode {
                    if let Err(error) = inspector::boot(rt) {
                        startup_error = Some(error);
                        return;
                    }
                } else {
                    boot_mode::boot(rt);
                }
                #[cfg(not(sk_devtools))]
                boot_mode::boot(rt);
                window::content_loaded();
                commit_boot_tree(rt);
            });
        });
        #[cfg(sk_devtools)]
        if let Some(error) = startup_error {
            let summary = format!("inspector startup failed: {error}");
            eprintln!("[native-aot] {summary}");
            embed::finished(false, summary);
            window::cancel_startup_reveal();
            cx.quit();
            return;
        }
        refresh_main(cx);
        #[cfg(target_os = "windows")]
        if defer_reveal {
            reveal_startup_window(cx, startup_focus);
        }
        // A hidden window has no frame callback to own the boot wave: start its background clock.
        if !embed::visible() {
            background::note_frame();
            reveal_if_unreachable(cx);
        }
        if !devtools_mode && !quiet::never_focus() && embed::activates() {
            cx.activate(true);
        }
        #[cfg(sk_devtools)]
        if devtools_mode {
            inspector::watch_parent();
        }
    });
}
