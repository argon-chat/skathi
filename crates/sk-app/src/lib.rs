thread_local! {
    static SHELL: RefCell<Option<WeakEntity<Shell>>> = const { RefCell::new(None) };
    /// The primary window itself, not its root view: the multi-window repaint fan-out runs inside
    /// input listeners, where the root view may already be borrowed.
    static MAIN_WINDOW: std::cell::Cell<Option<gpui::AnyWindowHandle>> =
        const { std::cell::Cell::new(None) };
}

/// The forced synchronous layout a DOM measurement asks for (`sk_tree::set_sync_layout`): draws the
/// primary window once. `with_app` is `None` inside a real frame, so this never runs inside a draw.
///
/// Unleased window (boot, first mount): through its handle. Later waves run leased, where
/// `handle.update` fails, so the draw goes through the window that wave published.
///
/// Never inside a gpui input listener: gpui has the frame's listeners taken out, and a draw would
/// swap the frame under them. The read stays stale there.
fn sync_layout() {
    let Some(handle) = MAIN_WINDOW.with(|w| w.get()) else { return };
    let draw = |window: &mut gpui::Window, cx: &mut gpui::App| sk_runtime::bridge::with_draw(|| window.draw(cx).clear(cx));
    let drew = sk_runtime::bridge::with_app(|cx| handle.update(cx, |_, window, cx| draw(window, cx)).is_ok());
    if drew != Some(false) || sk_tree::in_input_dispatch() {
        return;
    }
    sk_runtime::with_commit(|window, cx| {
        if window.window_handle() == handle {
            draw(window, cx);
        }
    });
}

fn commit_boot_tree(runtime: &JsRuntime) {
    // Vue's mount/load handlers may queue their last DOM writes in a microtask.
    runtime.ctx().drain_microtasks();
    sk_tree::flush_changes();
}

