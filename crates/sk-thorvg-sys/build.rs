//! Links a static ThorVG. `thorvg/` is the argon-chat/thorvg submodule (branch `vue-native`), an
//! upstream release tag with no local changes.
//!
//! Where the archive comes from, first match wins:
//! - `SK_THORVG_FROM_SOURCE=1`: compiled from `thorvg/` with `cc`.
//! - `SK_THORVG_DIR`: a directory holding a prebuilt `thorvg.lib` (MSVC) or `libthorvg.a`.
//! - The default features on a target `prebuilt.txt` lists: the pinned archive from its release,
//!   checked against its sha256 and cached (`SK_THORVG_CACHE_DIR`, else `$CARGO_HOME/sk-thorvg`).
//!   `SK_THORVG_RELEASE_URL` replaces the release URL; a local directory works too.
//! - Anything else, or a failed download, compiles from source.
//!
//! The prebuilt archives are this script's source build (.github/workflows/thorvg.yml), so a
//! change to the flags or sources below needs a new release in `prebuilt.txt`.
//!
//! No `bindgen` (the FFI declarations are checked in at `src/bindings.rs`, regenerated by
//! `tools/regen-bindings/`), no `cmake`/`meson`/`ninja` or `pkg-config`.
//!
//! A version bump: point the fork's `vue-native` branch and the submodule at the next upstream tag,
//! set `THORVG_VERSION` below, regenerate `src/bindings.rs`, publish its prebuilt release, then
//! `cargo test -p sk-thorvg-sys` (its first test checks the archive reports the version the
//! bindings were generated from).
//!
//! Hosted desktop platforms only (MSVC / GNU / Apple); any other host gets cc-rs defaults.

use std::env;
use std::fs;
use std::io::Read;
use std::path::{Path, PathBuf};
use std::process::Command;

use sha2::{Digest, Sha256};

const THORVG_VERSION: &str = "1.1.2";

fn main() {
    let out_dir = PathBuf::from(env::var("OUT_DIR").unwrap());
    let is_msvc = env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc");
    let target_os = env::var("CARGO_CFG_TARGET_OS").unwrap_or_default();
    let target_vendor = env::var("CARGO_CFG_TARGET_VENDOR").unwrap_or_default();
    let lib_file = if is_msvc { "thorvg.lib" } else { "libthorvg.a" };

    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-changed=prebuilt.txt");
    for var in [
        "SK_THORVG_FROM_SOURCE",
        "SK_THORVG_DIR",
        "SK_THORVG_RELEASE_URL",
        "SK_THORVG_CACHE_DIR",
    ] {
        println!("cargo:rerun-if-env-changed={var}");
    }

    let from_source =
        env::var_os("SK_THORVG_FROM_SOURCE").is_some_and(|v| !v.is_empty() && v != "0");
    let linked = !from_source
        && match env::var_os("SK_THORVG_DIR").filter(|v| !v.is_empty()) {
            Some(dir) => {
                let lib = Path::new(&dir).join(lib_file);
                if !lib.is_file() {
                    fail(&format!(
                        "SK_THORVG_DIR has no {lib_file}: {}",
                        lib.display()
                    ));
                }
                println!("cargo:rerun-if-changed={}", lib.display());
                fs::copy(&lib, out_dir.join(lib_file))
                    .unwrap_or_else(|e| fail(&format!("copying {}: {e}", lib.display())));
                true
            }
            None => match prebuilt(&out_dir, is_msvc, lib_file) {
                Ok(linked) => linked,
                Err(message) => {
                    println!("cargo:warning={message}; compiling ThorVG from source");
                    false
                }
            },
        };

    if linked {
        println!("cargo:rustc-link-search=native={}", out_dir.display());
    } else {
        compile(&out_dir, is_msvc);
    }

    println!("cargo:rustc-link-lib=static=thorvg");
    // cc-rs's automatic C++ runtime emission is unreliable; name it per platform (MSVC links it via the CRT choice).
    if target_vendor == "apple" || target_os == "freebsd" {
        println!("cargo:rustc-link-lib=dylib=c++");
    } else if !is_msvc && (target_os == "linux" || target_os == "android") {
        println!("cargo:rustc-link-lib=dylib=stdc++");
    }
}

fn fail(message: &str) -> ! {
    panic!("\n\nsk-thorvg-sys: {message}\n\n");
}

/// The cargo features the prebuilt archives are built with: the crate's defaults.
fn default_features() -> bool {
    cfg!(feature = "expressions")
        && cfg!(feature = "png")
        && cfg!(feature = "jpg")
        && cfg!(feature = "fonts")
        && cfg!(feature = "threads")
        && !cfg!(feature = "avx")
}

/// Windows has one archive per MSVC runtime: `mt` for `+crt-static`, `md` otherwise.
fn prebuilt_key(is_msvc: bool) -> String {
    let target = env::var("TARGET").unwrap();
    if !is_msvc {
        return target;
    }
    let features = env::var("CARGO_CFG_TARGET_FEATURE").unwrap_or_default();
    let crt = if features.split(',').any(|f| f == "crt-static") {
        "mt"
    } else {
        "md"
    };
    format!("{target}-{crt}")
}

/// Unpacks the pinned archive into `out_dir`. `Ok(false)` when there is none for this build.
fn prebuilt(out_dir: &Path, is_msvc: bool, lib_file: &str) -> Result<bool, String> {
    if !default_features() {
        return Ok(false);
    }
    let manifest = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("prebuilt.txt");
    let manifest =
        fs::read_to_string(&manifest).map_err(|e| format!("{}: {e}", manifest.display()))?;
    let ext = if is_msvc { "lib" } else { "a" };
    let archive = format!("thorvg-{THORVG_VERSION}-{}.{ext}.gz", prebuilt_key(is_msvc));
    let mut release = None;
    let mut sha256 = None;
    for line in manifest
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
    {
        match line.split_once(char::is_whitespace) {
            Some(("release", url)) => release = Some(url.trim()),
            Some((sum, name)) if name.trim().trim_start_matches('*') == archive => {
                sha256 = Some(sum)
            }
            _ => {}
        }
    }
    let Some(sha256) = sha256 else {
        return Ok(false);
    };
    let release = env::var("SK_THORVG_RELEASE_URL")
        .ok()
        .filter(|v| !v.is_empty())
        .or(release.map(str::to_owned))
        .ok_or("prebuilt.txt has no `release` line")?;

    let cached = cache_root().join(format!("{}-{archive}", sha256.get(..12).unwrap_or(sha256)));
    let bytes = match fs::read(&cached) {
        Ok(bytes) if hex_sha256(&bytes) == sha256 => bytes,
        _ => {
            let bytes = fetch(&release, &archive)?;
            let digest = hex_sha256(&bytes);
            if digest != sha256 {
                fail(&format!(
                    "{release}/{archive} has sha256 {digest}, expected {sha256}"
                ));
            }
            store(&cached, &bytes);
            bytes
        }
    };

    let mut lib = Vec::new();
    flate2::read::GzDecoder::new(&bytes[..])
        .read_to_end(&mut lib)
        .map_err(|e| format!("unpacking {archive}: {e}"))?;
    fs::write(out_dir.join(lib_file), lib).map_err(|e| format!("{}: {e}", out_dir.display()))?;
    Ok(true)
}

fn hex_sha256(bytes: &[u8]) -> String {
    Sha256::digest(bytes)
        .iter()
        .map(|b| format!("{b:02x}"))
        .collect()
}

/// `SK_THORVG_CACHE_DIR`, else `$CARGO_HOME/sk-thorvg`, so `cargo clean` does not force a download.
fn cache_root() -> PathBuf {
    if let Some(dir) = env::var_os("SK_THORVG_CACHE_DIR").filter(|v| !v.is_empty()) {
        return PathBuf::from(dir);
    }
    env::var_os("CARGO_HOME")
        .map(PathBuf::from)
        .or_else(|| {
            env::var_os("HOME")
                .or_else(|| env::var_os("USERPROFILE"))
                .map(|home| Path::new(&home).join(".cargo"))
        })
        .unwrap_or_else(|| PathBuf::from(env::var_os("OUT_DIR").unwrap()))
        .join("sk-thorvg")
}

/// A failed cache write only costs the next build a download.
fn store(path: &Path, bytes: &[u8]) {
    let Some(dir) = path.parent() else { return };
    let staging = dir.join(format!(".partial-{}", std::process::id()));
    let _ = fs::create_dir_all(dir);
    if fs::write(&staging, bytes)
        .and_then(|()| fs::rename(&staging, path))
        .is_err()
    {
        let _ = fs::remove_file(&staging);
    }
}

/// `release` is an http(s) URL (fetched with the system `curl`, which every supported host ships)
/// or a local directory, optionally as a `file://` URL.
fn fetch(release: &str, archive: &str) -> Result<Vec<u8>, String> {
    let release = release.trim_end_matches('/');
    if !(release.starts_with("https://") || release.starts_with("http://")) {
        let dir = release.strip_prefix("file://").unwrap_or(release);
        let dir = if cfg!(windows) && dir.starts_with('/') && dir.as_bytes().get(2) == Some(&b':') {
            &dir[1..]
        } else {
            dir
        };
        let path = Path::new(dir).join(archive);
        return fs::read(&path).map_err(|e| format!("{}: {e}", path.display()));
    }
    let url = format!("{release}/{archive}");
    let output = Command::new("curl")
        .args([
            "--fail",
            "--silent",
            "--show-error",
            "--location",
            "--retry",
            "3",
            &url,
        ])
        .output()
        .map_err(|e| format!("cannot run curl to download {url}: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "downloading {url}: {}",
            String::from_utf8_lossy(&output.stderr).trim()
        ));
    }
    Ok(output.stdout)
}

fn compile(out_dir: &Path, is_msvc: bool) {
    let thorvg = Path::new(&env::var("CARGO_MANIFEST_DIR").unwrap()).join("thorvg");
    let src = thorvg.join("src");
    println!("cargo:rerun-if-changed=thorvg");

    write_config_h(out_dir);

    let mut build = cc::Build::new();
    build.cpp(true).std("c++14").warnings(false);

    // Statically linked, so the C API must carry no dllimport/dllexport decoration (meson's
    // `-DTVG_STATIC`); MSVC otherwise rejects tvgCapi.cpp (C2491).
    build.define("TVG_STATIC", None);

    if is_msvc {
        // The Windows SDK's `min`/`max` macros break tvgMath.h (C2059); upstream's meson passes the same define.
        build.define("NOMINMAX", None);
        // The loaders use exceptions: /EHsc. cc-rs picks /MT from `+crt-static`, as .cargo/config.toml demands.
        build.flag("/EHsc");
        // `pragma GCC`/`#warning` noise from ThorVG's bundled JerryScript.
        build.flag("/wd4068");
        // The prebuilt comes from a runner's MSVC; its vectorized STL algorithms (`__std_min_element_f_`
        // and the rest) live in that toolset's libcpmt, which an older Visual Studio lacks.
        build.define("_USE_STD_VECTOR_ALGORITHMS", "0");
    } else {
        for flag in [
            "-fno-exceptions",
            "-fno-rtti",
            "-fno-stack-protector",
            "-fno-math-errno",
            "-Wno-unknown-pragmas",
        ] {
            build.flag_if_supported(flag);
        }
    }

    build.define("_DEFAULT_SOURCE", None);

    if cfg!(feature = "avx") && env::var("CARGO_CFG_TARGET_ARCH").as_deref() == Ok("x86_64") {
        // Off by default, as upstream's `simd=false`: AVX raises the CPU baseline to Sandy Bridge.
        if !is_msvc {
            build.flag_if_supported("-mavx");
        }
    }

    // JerryScript's `JERRY_VLA` fallback calls alloca() without <alloca.h>, which MSVC lacks; C99
    // VLAs are what the macro stands in for.
    if cfg!(feature = "expressions") {
        build.define("JERRY_VLA(type,name,size)", "type name[size]");
    }

    for dir in include_dirs(&thorvg, &src, out_dir) {
        build.include(dir);
    }
    for file in sources(&src) {
        build.file(file);
    }
    build.compile("thorvg");
}

/// The `.cpp` set for the enabled cargo features. GPU engines are never compiled.
fn sources(src: &Path) -> Vec<PathBuf> {
    let mut sources = Vec::new();
    push_cpp(&mut sources, &src.join("common"));
    push_cpp(&mut sources, &src.join("renderer"));
    push_cpp(&mut sources, &src.join("renderer/cpu_engine"));
    push_cpp(&mut sources, &src.join("bindings/capi"));
    push_cpp(&mut sources, &src.join("loaders/raw"));

    push_cpp(&mut sources, &src.join("loaders/lottie"));
    if cfg!(feature = "expressions") {
        push_cpp_recursive(&mut sources, &src.join("loaders/lottie/jerryscript"));
    } else {
        // The expressions TU includes JerryScript headers that are not on
        // the include path in this configuration.
        sources.retain(|path| !path.ends_with("tvgLottieExpressions.cpp"));
    }
    if cfg!(feature = "png") {
        push_cpp(&mut sources, &src.join("loaders/png"));
    }
    if cfg!(feature = "jpg") {
        push_cpp(&mut sources, &src.join("loaders/jpg"));
    }
    if cfg!(feature = "fonts") {
        push_cpp(&mut sources, &src.join("loaders/sfnt"));
    }
    sources
}

fn include_dirs(thorvg: &Path, src: &Path, out_dir: &Path) -> Vec<PathBuf> {
    let mut dirs = vec![
        out_dir.to_path_buf(), // the generated config.h
        thorvg.join("inc"),    // the public C++ header
        src.join("renderer"),
        src.join("renderer/cpu_engine"),
        src.join("common"),
        src.join("bindings/capi"),
        src.join("loaders/raw"),
        src.join("loaders/lottie"),
        src.join("loaders/lottie/rapidjson"),
    ];
    if cfg!(feature = "expressions") {
        let jerry = src.join("loaders/lottie/jerryscript");
        for sub in [
            "jerry-core",
            "jerry-core/include",
            "jerry-core/ecma/base",
            "jerry-core/ecma/builtin-objects",
            "jerry-core/ecma/builtin-objects/typedarray",
            "jerry-core/ecma/operations",
            "jerry-core/jcontext",
            "jerry-core/jmem",
            "jerry-core/jrt",
            "jerry-core/lit",
            "jerry-core/parser/js",
            "jerry-core/parser/regexp",
            "jerry-core/vm",
            "jerry-port/common",
        ] {
            dirs.push(jerry.join(sub));
        }
    }
    if cfg!(feature = "png") {
        dirs.push(src.join("loaders/png"));
    }
    if cfg!(feature = "jpg") {
        dirs.push(src.join("loaders/jpg"));
    }
    if cfg!(feature = "fonts") {
        dirs.push(src.join("loaders/sfnt"));
    }
    dirs
}

/// ThorVG's meson generates `config.h`; cargo features stand in for the meson options, tracking upstream's defaults.
fn write_config_h(out_dir: &Path) {
    let mut config = format!(
        "/* Generated by sk-thorvg-sys build.rs — do not edit. */\n\
         #pragma once\n\n\
         #define THORVG_VERSION_STRING \"{THORVG_VERSION}\"\n\
         #define THORVG_CAPI_BINDING_SUPPORT 1\n\
         #define THORVG_CPU_ENGINE_SUPPORT 1\n\
         #define THORVG_LOTTIE_LOADER_SUPPORT 1\n\
         #define THORVG_FILE_IO_SUPPORT 1\n\
         #define THORVG_PARTIAL_RENDER_SUPPORT 1\n",
    );
    if cfg!(feature = "threads") {
        config.push_str("#define THORVG_THREAD_SUPPORT 1\n");
    }
    if cfg!(feature = "expressions") {
        config.push_str("#define THORVG_LOTTIE_EXPRESSIONS_SUPPORT 1\n");
    }
    if cfg!(feature = "png") {
        config.push_str("#define THORVG_PNG_LOADER_SUPPORT 1\n");
    }
    if cfg!(feature = "jpg") {
        config.push_str("#define THORVG_JPG_LOADER_SUPPORT 1\n");
    }
    if cfg!(feature = "fonts") {
        config.push_str("#define THORVG_SFNT_LOADER_SUPPORT 1\n");
        config.push_str("#define THORVG_TTF_LOADER_SUPPORT 1\n");
        config.push_str("#define THORVG_OTF_LOADER_SUPPORT 1\n");
    }
    if cfg!(feature = "avx") {
        config.push_str("#define THORVG_AVX_VECTOR_SUPPORT 1\n");
    }
    fs::write(out_dir.join("config.h"), config).expect("write config.h");
}

fn push_cpp(out: &mut Vec<PathBuf>, dir: &Path) {
    let Ok(entries) = fs::read_dir(dir) else {
        panic!(
            "ThorVG source directory missing: {} (git submodule update --init)",
            dir.display()
        );
    };
    let mut found: Vec<PathBuf> = entries
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.extension().is_some_and(|ext| ext == "cpp"))
        .collect();
    found.sort();
    out.extend(found);
}

fn push_cpp_recursive(out: &mut Vec<PathBuf>, dir: &Path) {
    let mut stack = vec![dir.to_path_buf()];
    let mut found = Vec::new();
    while let Some(current) = stack.pop() {
        let Ok(entries) = fs::read_dir(&current) else {
            panic!(
                "ThorVG source directory missing: {} (git submodule update --init)",
                current.display()
            );
        };
        for path in entries.flatten().map(|entry| entry.path()) {
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|ext| ext == "cpp") {
                found.push(path);
            }
        }
    }
    found.sort();
    out.extend(found);
}
